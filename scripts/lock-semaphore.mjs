// Maintainer-only lock creation. Normal provisioning uses the committed lock.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { zKey } from "snarkjs";
if (!process.argv.includes("--update"))
  throw Error(
    "Maintainer operation: pass --update only when reviewing a new artifact lock.",
  );
const sdk = JSON.parse(
  readFileSync(
    "node_modules/@semaphore-protocol/proof/src/verification-keys.json",
    "utf8",
  ),
);
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
mkdirSync("spec/crypto", { recursive: true });
const depths = [];
for (const depth of [16, 26]) {
  const vk = {
    ...sdk,
    vk_delta_2: sdk.vk_delta_2[depth - 1],
    IC: sdk.IC[depth - 1],
  };
  const exported = await zKey.exportVerificationKey(
    `.tools/semaphore/${depth}/semaphore.zkey`,
  );
  for (const k of [
    "protocol",
    "curve",
    "nPublic",
    "vk_alpha_1",
    "vk_beta_2",
    "vk_gamma_2",
    "vk_delta_2",
    "IC",
  ])
    if (JSON.stringify(exported[k]) !== JSON.stringify(vk[k]))
      throw Error(`verification key mismatch: ${depth}/${k}`);
  const vkPath = `spec/crypto/semaphore-${depth}.verification-key.json`;
  writeFileSync(vkPath, JSON.stringify(vk, null, 2) + "\n");
  const files = {};
  for (const kind of ["wasm", "zkey"]) {
    const path = `.tools/semaphore/${depth}/semaphore.${kind}`,
      bytes = readFileSync(path);
    files[kind] = {
      file: `${depth}/semaphore.${kind}`,
      sha256: digest(bytes),
      size: String(bytes.length),
      source: `https://snark-artifacts.pse.dev/semaphore/4.13.0/semaphore-${depth}.${kind}`,
    };
  }
  const vkBytes = readFileSync(vkPath);
  files.verification_key = {
    file: vkPath,
    sha256: digest(vkBytes),
    size: String(vkBytes.length),
    source: "npm:@semaphore-protocol/proof@4.14.5/src/verification-keys.json",
  };
  depths.push({ depth: String(depth), ...files });
}
const lock = {
  sdk_version: "4.14.5",
  sdk_git_commit: "dbab5553c486a09d5e1042e5271e3316224cc176",
  sdk_source: "https://github.com/semaphore-protocol/semaphore/tree/v4.14.5",
  circuit_version: "4.13.0",
  lean_imt_version: JSON.parse(
    readFileSync("node_modules/@zk-kit/lean-imt/package.json", "utf8"),
  ).version,
  poseidon_lite_version: JSON.parse(
    readFileSync("node_modules/poseidon-lite/package.json", "utf8"),
  ).version,
  depths,
};
writeFileSync(
  "spec/crypto/semaphore-v4.lock.json",
  JSON.stringify(lock, null, 2) + "\n",
);
writeFileSync(
  "web/src/semaphore-lock.ts",
  "// Generated by scripts/lock-semaphore.mjs. Never accept artifacts from a voter.\nexport const semaphoreLock = " +
    JSON.stringify(lock, null, 2) +
    " as const;\n",
);
if (globalThis.curve_bn128) await globalThis.curve_bn128.terminate();
